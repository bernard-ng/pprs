#!/usr/bin/env python3
"""Regenerate (--write) or reproduce (--check) the P02 oracle. Requires pinned PHP."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

from verify_p00 import verify_metadata, verify_checkout

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / 'tests/fixtures/upstream'


def encoded(value):
    return (json.dumps(value, ensure_ascii=True, separators=(',', ':')) + '\n').encode()


def generate(root=ROOT):
    lock, files, grammar, fixtures = verify_metadata(root)
    verify_checkout(root / '.references', lock, files, grammar, fixtures)
    result = subprocess.run(['php', '-n', '-d', 'short_open_tag=0', '-d', 'precision=14',
                             '-d', 'serialize_precision=-1', '-d', 'display_errors=stderr',
                             str(root / 'tools/reference/export.php')], check=True, capture_output=True)
    if result.stderr:
        raise ValueError(result.stderr.decode())
    exported = json.loads(result.stdout)
    profile = exported['profile']
    profile_id = hashlib.sha256(encoded(profile)).hexdigest()
    records = exported['cases']
    for record in records:
        record['profile_id'] = profile_id
    assets = {'cases.jsonl': b''.join(encoded(record) for record in records),
              'deferred-printer.jsonl': b''.join(encoded(row) for row in fixtures
                                                if not row['id'].startswith('parser/')),
              'LICENSE': (root / lock['license_path']).read_bytes()}
    for path in sorted({r['origin']['path'] for r in records if r['origin']}):
        assets['raw/' + path.removeprefix('test/code/')] = (root / '.references' / path).read_bytes()
    sources = ['bootstrap.php', 'normalize.php', 'export.php', 'export.py', 'inputs.json']
    manifest = {
        'schema_version': 1, 'exporter_version': 1, 'reference_commit': lock['commit'],
        'reference_manifest_sha256': lock['file_manifest_sha256'],
        'profile_id': profile_id, 'profile': profile,
        'exporter_sha256': {name: hashlib.sha256((root / 'tools/reference' / name).read_bytes()).hexdigest()
                            for name in sources},
        'counts': {'original_parser': 290, 'derived': 4, 'project': 19, 'printer_deferred': 240,
                   'total': len(records)},
        'files': {name: hashlib.sha256(data).hexdigest() for name, data in sorted(assets.items())},
    }
    assets['manifest.json'] = json.dumps(manifest, indent=2).encode() + b'\n'
    return assets


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assets = generate()
    # Validate before replacing any committed file; coverage state is never regenerated.
    with tempfile.TemporaryDirectory(prefix='pprs-export-') as directory:
        staged = Path(directory)
        for name, data in assets.items():
            path = staged / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        from corpus import validate
        validate(staged, ROOT)
        if args.check:
            for name, data in assets.items():
                if (DESTINATION / name).read_bytes() != data:
                    raise ValueError(f'Non-reproducible export: {name}')
            print('P02 export reproduces every committed generated byte.')
        else:
            for name, data in assets.items():
                path = DESTINATION / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
            print(f'Wrote {len(assets)} generated files; coverage states were not changed.')


if __name__ == '__main__':
    main()
